import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 1440, height: 900 } })

test('mouse actions check an answer, retry, change parts, and replay without losing progress', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/?section=11&page=calculate-expression&exercise=11.1')
  await expect(page.getByText('0 из 284 решено')).toBeVisible()
  await expect(page.getByRole('status')).toHaveText('')
  await expect(page.getByText(/показатели складываются/)).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Ответ', exact: true }).fill('64')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Пока неверно')
  await page.getByRole('textbox', { name: 'Ответ', exact: true }).fill('32')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Верно')
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('desktop-correct.png'), fullPage: true })
  for (const [letter, answer] of [['б', '343'], ['в', '3'], ['г', '27/64']]) {
    await page.getByRole('button', { name: `Часть ${letter}`, exact: true }).click()
    await page.getByRole('textbox', { name: 'Ответ', exact: true }).fill(answer)
    await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  }
  await expect(page.getByText('Все части упражнения 11.1 решены.')).toBeVisible()
  await page.getByRole('button', { name: 'Решить ещё раз' }).click()
  await expect(page.getByRole('textbox', { name: 'Ответ', exact: true })).toHaveValue('')
  await page.getByRole('textbox', { name: 'Ответ', exact: true }).fill('0')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await page.reload()
  await expect(page.getByText('4 из 284 решено')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Часть а — решено' })).toBeVisible()
  expect(errors).toEqual([])
})

test('keyboard actions classify a function and enter three values', async ({ page }, testInfo) => {
  await page.goto('/?section=11&page=identify-functions&exercise=11.9')
  const yes = page.getByRole('radio', { name: 'Показательная', exact: true })
  await yes.focus()
  await page.keyboard.press('Space')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Число π')
  await page.getByRole('button', { name: 'Часть б', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toHaveText('')
  await page.getByRole('radio', { name: 'Не показательная', exact: true }).focus()
  await page.keyboard.press('Space')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Постоянный показатель π')
  await page.goto('/?section=11&page=find-function-value&exercise=11.10')
  await page.getByRole('textbox', { name: 'y₁', exact: true }).focus()
  await page.keyboard.type('343')
  await page.keyboard.press('Tab')
  await page.keyboard.type('1/7')
  await page.keyboard.press('Tab')
  await page.keyboard.type('sqrt(7)')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('y₃ = √7')
  await page.screenshot({ path: testInfo.outputPath('desktop-values.png'), fullPage: true })
})

test('tree exposes all twelve optional exercises and section 12 remains accessible', async ({ page }) => {
  await page.goto('/?section=11&page=calculate-expression')
  await page.getByRole('button', { name: 'Открыть дерево книги' }).click()
  const tree = page.getByRole('navigation', { name: 'Дерево книги' })
  await expect(tree.getByRole('button', { name: /^Упражнение 11\./ })).toHaveCount(12)
  await tree.getByRole('button', { name: 'Упражнение 11.12', exact: true }).click()
  await expect(page).toHaveURL(/exercise=11.12/)
  await page.getByRole('button', { name: 'Закрыть дерево книги' }).click()
  await expect(page.getByRole('heading', { name: 'Упражнение 11.12' })).toBeVisible()
  await page.getByRole('button', { name: 'Открыть дерево книги' }).click()
  await tree.getByText('§12. Показательные уравнения', { exact: true }).click()
  await tree.getByRole('button', { name: '§12. Показательные уравнения — 📖 Теория' }).click()
  await expect(page).toHaveURL(/section=12&page=theory/)
  await page.getByRole('button', { name: 'Закрыть дерево книги' }).click()
  await expect(page.getByRole('heading', { name: '§12. Показательные уравнения' })).toBeVisible()
})

test('a radical part remains usable on a narrow screen', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?section=11&page=calculate-expression&exercise=11.7')
  await page.getByRole('button', { name: 'Часть г', exact: true }).click()
  await expect(page.getByText('root(3;2)', { exact: false })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Ответ', exact: true }).fill('root(3;2)')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('∛2')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mobile-radical.png'), fullPage: true })
})
