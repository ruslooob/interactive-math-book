import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 1440, height: 900 } })

test.beforeEach(async ({ page }) => {
  await page.goto('/?section=11&page=draw-graph&exercise=11.13')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
})

test('mouse graph construction, retry, saved progress, and immediate replay', async ({ page }) => {
  await expect(page.getByRole('heading', { name: 'Упражнение 11.13 · а' })).toBeVisible()
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('введите значения трёх опорных точек')
  await expect(page.getByText('0 из 284 решено')).toBeVisible()
  await page.getByLabel('График 1: y(-1)', { exact: true }).fill('1/sqrt(2)')
  await page.getByLabel('График 1: y(0)', { exact: true }).fill('1')
  await page.getByLabel('График 1: y(1)', { exact: true }).fill('sqrt(2)')
  await page.getByLabel('Область определения', { exact: true }).selectOption('real')
  await page.getByLabel('Область значений', { exact: true }).selectOption('positive')
  await page.getByLabel('Асимптота', { exact: true }).selectOption('y0')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Точки, области и асимптота верны')
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
  await page.getByRole('img', { name: 'Эскиз по введённым точкам' }).screenshot({ path: 'tmp/graph-correct.png' })
  await page.getByRole('button', { name: 'Решить снова' }).click()
  await expect(page.getByLabel('График 1: y(1)', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
  await expect(page.getByText('Простой уровень · Решено')).toBeVisible()
})

test('keyboard comparison, exercise and part navigation, and unrestricted section 12', async ({ page }) => {
  await page.goto('/?section=11&page=compare-values&exercise=11.18')
  const less = page.getByRole('button', { name: 'Меньше', exact: true })
  await less.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Проверьте сравнение показателей')
  await less.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Верно.')
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
  await page.getByRole('button', { name: 'б', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Упражнение 11.18 · б' })).toBeVisible()
  await expect(page.getByRole('status')).toHaveCount(0)
  await page.getByLabel('Упражнение', { exact: true }).focus()
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Упражнение 11.17 · а' })).toBeVisible()
  await page.goto('/?section=11&page=find-integer-values')
  await page.getByRole('button', { name: '§12. Показательные уравнения' }).click()
  await expect(page.getByRole('heading', { name: '§12. Показательные уравнения' })).toBeVisible()
})

test('keyboard ordering checks learner moves and retains the solved part', async ({ page }) => {
  await page.goto('/?section=11&page=compare-values&exercise=11.24')
  await page.getByRole('button', { name: 'б', exact: true }).click()
  await expect(page.getByText('○ Средний уровень')).toBeVisible()
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Проверьте основание')
  // Source values start in reverse order: v3, v2, v1. Move v1 up twice, then v3 down.
  await page.getByRole('button', { name: 'Позиция 3: выше', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Позиция 2: выше', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Позиция 2: ниже', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Проверить', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Порядок верен')
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
  await page.screenshot({ path: 'tmp/ordering-correct.png', fullPage: true })
  await page.getByRole('button', { name: 'Решить снова' }).click()
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
})

test('book tree exposes all 13 exercises and shared graphs use common axes', async ({ page }) => {
  await page.getByRole('button', { name: 'Открыть дерево книги' }).click()
  const tree = page.getByRole('navigation', { name: 'Дерево книги' })
  await expect(tree.getByRole('button', { name: /^Упражнение 11\./ })).toHaveCount(13)
  await tree.getByRole('button', { name: 'Упражнение 11.16', exact: true }).click()
  await page.getByRole('button', { name: 'в', exact: true }).click()
  await expect(page.locator('fieldset')).toHaveCount(3)
  await expect(page.getByRole('img', { name: 'Эскиз по введённым точкам' })).toHaveCount(1)
  const points = [['1/sqrt(7)', '1', 'sqrt(7)'], ['1/5', '1', '5'], ['1/sqrt(8)', '1', 'sqrt(8)']]
  for (const [index, row] of points.entries()) for (const [column, value] of row.entries()) await page.getByLabel(`График ${index + 1}: y(${column - 1})`, { exact: true }).fill(value)
  await page.getByLabel('Область определения', { exact: true }).selectOption('real')
  await page.getByLabel('Область значений', { exact: true }).selectOption('positive')
  await page.getByLabel('Асимптота', { exact: true }).selectOption('y0')
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Точки, области и асимптота верны')
  await page.getByRole('img', { name: 'Эскиз по введённым точкам' }).screenshot({ path: 'tmp/shared-graph-sketch.png' })
  await page.screenshot({ path: 'tmp/shared-graph.png', fullPage: true })
  await page.getByRole('button', { name: 'Закрыть дерево книги' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('keyboard completes a graph without a mouse', async ({ page }) => {
  await page.getByLabel('График 1: y(-1)', { exact: true }).focus()
  await page.keyboard.insertText('1/sqrt(2)')
  await page.keyboard.press('Tab')
  await page.keyboard.insertText('1')
  await page.keyboard.press('Tab')
  await page.keyboard.insertText('sqrt(2)')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Точки, области и асимптота верны')
  await expect(page.getByText('1 из 284 решено')).toBeVisible()
})
