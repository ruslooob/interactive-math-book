import type { ExerciseContent, ExercisePartContent } from './exerciseContent'
import type { ExercisePartId } from './paragraph11Catalog'
import { numericAnswer } from '../lib/numericAnswer'

type ValueRow = readonly [formula: string, answers: readonly number[], explanation: string, result: string]
const suffixes = ['a', 'b', 'v', 'g'] as const

function valuesExercise(number: number, rows: readonly ValueRow[], question = 'Вычислите результат.', labels?: readonly string[]): ExerciseContent {
  return {
    exerciseId: `11.${number}`, status: 'ready',
    parts: rows.map(([formula, expected, explanation, result], index): ExercisePartContent<'calculated-values'> => ({
      id: `11.${number}-${suffixes[index]}` as ExercisePartId,
      kind: 'calculated-values',
      prompt: [{ kind: 'text', value: question }, { kind: 'formula', value: formula }],
      answerLabels: labels ?? expected.map(() => 'Ответ'),
      checkAnswer: ({ values }) => {
        const entered = values.map(numericAnswer)
        if (values.length !== expected.length || entered.some((value) => value === null)) {
          return { correct: false, feedback: 'Заполните каждый ответ числом, дробью или выражением с корнем.' }
        }
        const correct = values.length === expected.length && entered.every((value, i) => value !== null
          && Math.abs(value - expected[i]) <= 1e-10 * Math.max(1, Math.abs(expected[i])))
        const wrongIndex = entered.findIndex((value, i) => value !== null && Math.abs(value - expected[i]) > 1e-10 * Math.max(1, Math.abs(expected[i])))
        const field = labels && wrongIndex >= 0 ? ` Проверьте ${labels[wrongIndex]}.` : ''
        return { correct, feedback: correct ? `${explanation} ${result}` : `${explanation}${field} Вычислите ещё раз.` }
      },
    })),
  }
}

function classificationExercise(number: number, formulas: readonly string[], reasons: readonly string[]): ExerciseContent {
  return {
    exerciseId: `11.${number}`, status: 'ready',
    parts: formulas.map((formula, index): ExercisePartContent<'choices'> => ({
      id: `11.${number}-${suffixes[index]}`, kind: 'choices',
      prompt: [{ kind: 'text', value: 'Определите, является ли эта функция показательной.' }, { kind: 'formula', value: formula }],
      choices: [{ id: 'exponential', label: 'Показательная' }, { id: 'not-exponential', label: 'Не показательная' }],
      checkAnswer: ({ selectedIds }) => ({
        correct: selectedIds.length === 1 && selectedIds[0] === (index === 0 || index === 3 ? 'exponential' : 'not-exponential'),
        feedback: reasons[index],
      }),
    })),
  }
}

